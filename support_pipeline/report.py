"""WRITE_RESULTS: results.json (required schema only) plus debug_report.json / debug_report.md."""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Dict, List

from .schemas import TicketResult


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    os.replace(tmp, path)


def results_json(results: List[TicketResult]) -> str:
    return json.dumps([r.model_dump() for r in results], indent=2, ensure_ascii=False) + "\n"


def _markdown(debug: List[Dict], meta: Dict, summary: Dict) -> str:
    c = meta["components"]
    lines = [
        "# Debug report",
        "",
        f"Components: classifier=`{c['classifier']}`, retriever=`{c['retriever']}`, generator=`{c['generator']}`  ",
        f"Tickets: {summary['tickets']} | escalated: {summary['escalated']} | fallbacks: {summary['fallbacks']}",
        "",
    ]
    for note in meta.get("notes", []) + meta.get("warnings", []):
        lines.append(f"> Note: {note}")
    lines += ["", "| Ticket | Intent | Retrieved | Confidence | Escalate | Flags |", "|---|---|---|---|---|---|"]
    for d in debug:
        if "error" in d:
            lines.append(f"| {d['ticket_id']} | other (error) | — | 0.00 | yes | {', '.join(d['safety_flags'])} |")
            continue
        hits = ", ".join(f"{h['article_id']} {h['title']}" for h in d["retrieval"]["hits"]) or "—"
        lines.append(f"| {d['ticket_id']} | {d['intent']['label']} | {hits} | {d['confidence']['final']:.2f} | "
                     f"{'yes' if d['escalation']['escalate'] else 'no'} | {', '.join(d['safety_flags']) or '—'} |")
    for d in debug:
        lines += ["", f"## {d['ticket_id']}", "", f"> {d['message'] or '(empty message)'}", ""]
        if "error" in d:
            lines += [f"- **Processing error:** {d['error']}", "- **Escalated:** yes (safe fallback result)"]
            continue
        i, r, g, conf = d["intent"], d["retrieval"], d["generation"], d["confidence"]
        terms = "; ".join(f"{k}: {', '.join(v)}" for k, v in i["matched_terms"].items()) or "none"
        lines.append(f"- **Intent:** `{i['label']}` (certainty {i['certainty']:.2f}, via {i['component']})"
                     + (f" — advice guard fired" if i["advice_detected"] else ""))
        lines.append(f"  - matched terms: {terms}")
        if i.get("rationale"):
            lines.append(f"  - model rationale: {i['rationale']}")
        lines.append(f"- **Retrieved ({r['component']}):**" + ("" if r["hits"] else " none above threshold"))
        for h in r["hits"]:
            parts = ", ".join(f"{k}={v:.3f}" for k, v in h["components"].items())
            lines.append(f"  - {h['article_id']} — {h['title']} (topic `{h['topic']}`, score {h['score']:.3f}; {parts})")
        lines.append(f"- **Reply generated by:** {g['component']}")
        lines.append(f"- **Grounded:** {'yes' if d['grounding']['grounded'] else 'no'} "
                     f"(grounding score {d['grounding']['score']:.2f})")
        pen = ", ".join(f"{k} (-{v})" for k, v in conf["penalties"].items()) or "none"
        lines.append(f"- **Confidence:** {conf['final']:.2f} = 0.4×classifier {conf['classifier_certainty']:.2f} "
                     f"+ 0.4×retrieval {conf['retrieval_strength']:.2f} + 0.2×grounding {conf['grounding_score']:.2f}; "
                     f"penalties: {pen}")
        verdict = "escalated" if d["escalation"]["escalate"] else "not escalated"
        lines.append(f"- **Escalation:** {verdict} — {'; '.join(d['escalation']['reasons'])}")
        fallbacks = [x for x in (i["fallback"], r["fallback"], g["fallback"], *g["repairs"]) if x]
        if fallbacks:
            lines.append(f"- **Fallbacks:** {'; '.join(fallbacks)}")
    return "\n".join(lines) + "\n"


def write_results(results: List[TicketResult], debug: List[Dict], meta: Dict, out_dir: Path) -> Dict:
    fallbacks = sum(
        1 for d in debug
        if "error" in d or any([d["intent"]["fallback"], d["retrieval"]["fallback"], d["generation"]["fallback"],
                                d["generation"]["repairs"]])
    )
    summary = {
        "tickets": len(results),
        "escalated": sum(r.needs_human_escalation for r in results),
        "fallbacks": fallbacks,
        "components": meta["components"],
        "notes": meta.get("notes", []) + meta.get("warnings", []),
    }
    _atomic_write(out_dir / "results.json", results_json(results))
    _atomic_write(out_dir / "debug_report.json",
                  json.dumps({"run": {**meta, "summary": summary}, "tickets": debug}, indent=2, ensure_ascii=False) + "\n")
    _atomic_write(out_dir / "debug_report.md", _markdown(debug, meta, summary))
    return summary
